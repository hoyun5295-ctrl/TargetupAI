// ★ 컨트롤타워 — 청구 금액의 원 단위 처리와 부가세 산출. (2026-07-26 Harold 지시)
//
// 배경: 단가는 소수 둘째 자리까지 존재한다(예: LMS 22.80, SMS 7.20). 그래서 `수량 × 단가`가
// 소수로 떨어지고, 그 값이 그대로 청구서에 인쇄돼 `₩13,397,454.84` 같은 금액이 나갔다.
// 세금계산서는 원 단위이고, PDF 표의 금액 칸도 소수 두 자리가 붙으면 폭을 넘겨 줄바꿈으로 깨진다
// (2026-07-26 금강제화 정산서 2페이지 합계 실측).
//
// 원칙 — **원 미만은 버린다(절사).**
//   1. 절사 지점은 `billing_items` **행 단위**다. 그래야 그 위의 모든 합(유형별 줄 · 채널 · 장 ·
//      공급가액 · 부가세 · 합계)이 정수 덧셈이 되고, 고객이 청구서 1페이지 항목표를 세로로 더한 값과
//      2페이지 일자별 상세를 세로로 더한 값이 **둘 다** 공급가액과 정확히 맞는다.
//      총액에서 한 번만 절사하면 두 표의 세로합이 어긋난다 — 그게 ②를 단독 배포 못 했던 그 증상이다.
//   2. 반올림이 아니라 절사인 이유: 고객에게 불리한 방향으로 1원도 넘어가지 않게 한다.
//      우리 쪽 손실은 행당 최대 1원 미만이다.
//
// 부동소수점 주의: `6795 × 7.92`가 `53816.399999...`로 떨어지듯 곱셈 결과에 오차가 실린다.
// 그대로 `Math.floor`를 하면 정확히 정수여야 하는 값(`720 × 7 = 5040`)이 `5039`가 될 수 있다.
// 그래서 **먼저 소수 둘째 자리로 반올림해 오차를 걷어낸 뒤** 절사한다.

/** 부가세율 — 청구서·정산서 공통 */
export const VAT_RATE = 0.1;

/**
 * (순수) 원 미만 절사. 부동소수점 오차를 소수 둘째 자리 반올림으로 걷어낸 뒤 버린다.
 *
 * `floorWon(53816.4) === 53816` · `floorWon(5039.9999999) === 5040` · `floorWon(-0.4) === 0`
 * 음수는 0으로 올린다 — 청구 금액에 음수가 들어갈 자리가 없고, 들어오면 절사가 손실을 키운다.
 */
export function floorWon(value: number | string | null | undefined): number {
  const v = Number(value);
  if (!Number.isFinite(v)) return 0;
  if (v <= 0) return 0;
  return Math.floor(Math.round(v * 100) / 100);
}

/**
 * (순수) 공급가액 → 부가세. 공급가액이 정수라도 10%는 소수가 될 수 있어(13,397,443 → 1,339,744.3)
 * 같은 절사 규칙을 적용한다. 합계(`공급가액 + 부가세`)도 정수가 된다.
 */
export function vatOfSupply(subtotal: number | string | null | undefined): number {
  return floorWon(Number(subtotal || 0) * VAT_RATE);
}

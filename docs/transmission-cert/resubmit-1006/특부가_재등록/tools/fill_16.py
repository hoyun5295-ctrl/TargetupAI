def set_cell(cell, text):
    paras = cell.paragraphs
    p0 = paras[0]
    r0 = p0.runs[0] if p0.runs else None
    rpr = copy.deepcopy(r0._r.rPr) if (r0 is not None and r0._r.rPr is not None) else None
    for p in paras[1:]:
        p._p.getparent().remove(p._p)
    for r in list(p0._p.findall(qn('w:r'))):
        p0._p.remove(r)

    def add(p, t):
        r = p.add_run(t)
        if rpr is not None:
            r._r.insert(0, copy.deepcopy(rpr))

    lines = str(text).split('\n')
    add(p0, lines[0])
    prev = p0
    for ln in lines[1:]:
        np_el = copy.deepcopy(p0._p)
        for r in list(np_el.findall(qn('w:r'))):
            np_el.remove(r)
        prev._p.addnext(np_el)
        np_ = Paragraph(np_el, p0._parent)
        add(np_, ln)
        prev = np_


def uniq_cells(row):
    seen, out = set(), []
    for c in row.cells:
        if id(c._tc) in seen:
            continue
        seen.add(id(c._tc))
        out.append(c)
    return out


def fill_rows(tb, start, rows):
    """start 행부터의 샘플 행을 모두 지우고, 첫 샘플 행 모양으로 rows 를 새로 만든다."""
    tmpl = copy.deepcopy(tb.rows[start]._tr)
    while len(tb.rows) > start:
        tr = tb.rows[-1]._tr
        tr.getparent().remove(tr)
    for vals in rows:
        tb._tbl.append(copy.deepcopy(tmpl))
        cells = uniq_cells(tb.rows[-1])
        assert len(cells) == len(vals), (len(cells), vals)
        for c, v in zip(cells, vals):
            set_cell(c, v)


